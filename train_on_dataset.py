# Feature Extraction
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

def extract_all(paths: list, label: int, desc: str):
    X, y = [], []
    for fp in tqdm(paths, desc=desc):
        try:
            wav  = preprocess_audio(fp)
            if wav is None:
                continue
            feat = extract_features_for_cnn(wav)
            X.append(feat); y.append(label)
        except Exception as e:
            pass
    return X, y


def build_dataset(real_paths, fake_paths):
    print(f"\n[INFO] Extracting MFCCs from {len(real_paths)} real + {len(fake_paths)} fake clips...")
    Xr, yr = extract_all(real_paths, 0, "Real MFCC")
    Xf, yf = extract_all(fake_paths, 1, "Fake MFCC")
    X = np.array(Xr + Xf, dtype=np.float32)
    y = np.array(yr + yf, dtype=np.float32)
    print(f"[INFO] Dataset: {X.shape}, Real={len(yr)}, Fake={len(yf)}")
    return X, y


# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
# Training
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

def train(X, y, EPOCHS, BATCH_SIZE):
    from sklearn.model_selection import train_test_split

    Xp = X[:, :, :, 0][:, np.newaxis, :, :].astype(np.float32)
    yp = y.astype(np.float32).reshape(-1, 1)

    Xt, Xtmp, yt, ytmp = train_test_split(Xp, yp, test_size=0.30, random_state=SEED, stratify=yp)
    Xv, Xte, yv, yte   = train_test_split(Xtmp, ytmp, test_size=0.50, random_state=SEED, stratify=ytmp)

    def loader(Xa, ya, shuffle=True, augment=False):
        if augment:
            # Apply SpecAugment on-the-fly each epoch (new random masks)
            Xa = np.array([
                spec_augment(x[0])[np.newaxis] if np.random.random() < 0.6 else x
                for x in Xa
            ], dtype=np.float32)
        ds = TensorDataset(torch.from_numpy(Xa), torch.from_numpy(ya))
        return DataLoader(ds, batch_size=BATCH_SIZE, shuffle=shuffle, num_workers=0)

    vl_loader = loader(Xv, yv, shuffle=False)
    print(f"[INFO] Train={len(Xt)}, Val={len(Xv)}, Test={len(Xte)}")

    model, optim, _ = build_cnn_model(learning_rate=5e-4)
    sched  = torch.optim.lr_scheduler.CosineAnnealingLR(optim, T_max=EPOCHS)
    n0, n1 = float((yt==0).sum()), float((yt==1).sum())
    pw     = torch.tensor([n0/max(n1,1)]).to(DEVICE)
    loss_fn = nn.BCEWithLogitsLoss(pos_weight=pw)
    model.classifier[-1] = nn.Identity()

    hist = {"tl":[], "vl":[], "ta":[], "va":[]}
    best, pat = float("inf"), 0
    PATIENCE = 8

    for ep in range(1, EPOCHS+1):
        # Re-create train loader each epoch so SpecAugment masks differ
        tr = loader(Xt, yt, shuffle=True, augment=True)
        model.train()
        tl, tok, tn = 0.0, 0, 0
        for Xb, yb in tr:
            Xb, yb = Xb.to(DEVICE), yb.to(DEVICE)
            optim.zero_grad()
            logits = model(Xb)
            loss   = loss_fn(logits, yb)
            loss.backward()
            nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            optim.step()
            tl  += loss.item()*len(Xb)
            tok += ((torch.sigmoid(logits)>=0.5).float()==yb).sum().item()
            tn  += len(Xb)
        tl/=tn; ta=tok/tn

        model.eval()
        vl, vok, vn = 0.0, 0, 0
        with torch.no_grad():
            for Xb, yb in vl_loader:
                Xb, yb = Xb.to(DEVICE), yb.to(DEVICE)
                logits  = model(Xb)
                vl     += loss_fn(logits,yb).item()*len(Xb)
                vok    += ((torch.sigmoid(logits)>=0.5).float()==yb).sum().item()
                vn     += len(Xb)
        vl/=vn; va=vok/vn; sched.step()
        hist["tl"].append(tl); hist["vl"].append(vl)
        hist["ta"].append(ta); hist["va"].append(va)
        print(f"  Epoch {ep:3d}/{EPOCHS} | loss {tl:.4f} acc {ta*100:.1f}% | val_loss {vl:.4f} val_acc {va*100:.1f}%")

        if vl < best-1e-4:
            best=vl; pat=0; torch.save(model.state_dict(), "best_cnn.pt")
        else:
            pat+=1
            if pat>=PATIENCE:
                print(f"[INFO] Early stopping at epoch {ep}.")
                break

    model.load_state_dict(torch.load("best_cnn.pt", map_location=DEVICE))
    model.eval()
    model.classifier[-1] = nn.Sigmoid()
    return model, hist, Xte, yte


