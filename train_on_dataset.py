def load_from_csv(dataset_root: Path):
    """Load file lists from metadata.csv."""
    import csv
    real_paths, fake_paths = [], []
    csv_path = dataset_root / "metadata.csv"
    if not csv_path.exists():
        raise FileNotFoundError(f"metadata.csv not found at {csv_path}")
    with open(csv_path, encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            label = int(row["label"])
            lang  = row["language"]
            fname = row["filename"]
            # reconstruct full path
            subdir = "real" if label == 0 else "fake"
            full   = dataset_root / subdir / lang / fname
            if full.exists():
                (real_paths if label == 0 else fake_paths).append(str(full))
    return real_paths, fake_paths


def load_from_dirs(dataset_root: Path):
    """Scan real/ and fake/ subdirectories for WAV files."""
    real_dir = dataset_root / "real"
    fake_dir = dataset_root / "fake"
    real_paths = sorted(real_dir.rglob("*.wav"))
    fake_paths = sorted(fake_dir.rglob("*.wav"))
    return [str(p) for p in real_paths], [str(p) for p in fake_paths]


