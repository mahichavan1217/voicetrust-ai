# Evaluation + plots
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

def evaluate(model, Xte, yte):
    from sklearn.metrics import (accuracy_score, precision_score,
                                 recall_score, f1_score, confusion_matrix,
                                 classification_report)
    import seaborn as sns

    model.eval()
    Xp = torch.from_numpy(Xte).to(DEVICE)
    with torch.no_grad():
        probs = model(Xp).cpu().numpy().ravel()
    yp = (probs>=0.5).astype(int)
    yt = yte.astype(int).ravel()

    print(f"\n{'-'*45}")
    print(f"  Accuracy  : {accuracy_score(yt, yp)*100:.2f} %")
    print(f"  Precision : {precision_score(yt, yp, zero_division=0)*100:.2f} %")
    print(f"  Recall    : {recall_score(yt, yp, zero_division=0)*100:.2f} %")
    print(f"  F1-Score  : {f1_score(yt, yp, zero_division=0)*100:.2f} %")
    print(f"{'-'*45}\n")
    print(classification_report(yt, yp, target_names=["Real","Fake"]))

    cm = confusion_matrix(yt, yp)
    plt.figure(figsize=(6,5))
    sns.heatmap(cm, annot=True, fmt="d", cmap="Blues",
                xticklabels=["Real","Fake"], yticklabels=["Real","Fake"])
    plt.title("Confusion Matrix - IndicFakeSpeech")
    plt.tight_layout()
    Path("plots").mkdir(exist_ok=True)
    plt.savefig("plots/confusion_matrix.png", dpi=150)
    print("[INFO] Saved plots/confusion_matrix.png")


def plot_history(hist):
    fig, ax = plt.subplots(1, 2, figsize=(12,4))
    ax[0].plot(hist["ta"], label="Train"); ax[0].plot(hist["va"], label="Val")
    ax[0].set_title("Accuracy"); ax[0].legend(); ax[0].grid(alpha=.3)
    ax[1].plot(hist["tl"], label="Train"); ax[1].plot(hist["vl"], label="Val")
    ax[1].set_title("Loss"); ax[1].legend(); ax[1].grid(alpha=.3)
    plt.tight_layout()
    plt.savefig("plots/training_curves.png", dpi=150)
    print("[INFO] Saved plots/training_curves.png")


