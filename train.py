def _extract(fp: str):
    try:
        wav = preprocess_audio(fp)
        return None if wav is None else extract_features_for_cnn(wav)
    except Exception as e:
        print(f"  [WARN] {fp}: {e}")
        return None


def build_dataset(real_paths: list, fake_paths: list):
    print("\n" + "=" * 60)
    print("STEP 3 - Extracting MFCC Features")
    print("=" * 60)
    X_list, y_list = [], []
    print(f"[INFO] Extracting from {len(real_paths)} real clips ...")
    for fp in tqdm(real_paths, desc="Real MFCC"):
        feat = _extract(fp)
        if feat is not None:
            X_list.append(feat)
            y_list.append(0)   # real = 0
    print(f"[INFO] Extracting from {len(fake_paths)} fake clips ...")
    for fp in tqdm(fake_paths, desc="Fake MFCC"):
        feat = _extract(fp)
        if feat is not None:
            X_list.append(feat)
            y_list.append(1)   # fake = 1
    X = np.array(X_list, dtype=np.float32)
    y = np.array(y_list, dtype=np.float32)
    real_n = int((y == 0).sum())
    fake_n = int((y == 1).sum())
    print(f"[INFO] Dataset: X={X.shape}, Real={real_n}, Fake={fake_n}")
    if real_n < 10 or fake_n < 10:
        raise RuntimeError(f"Too few samples: Real={real_n}, Fake={fake_n}. Check data sources.")
    return X, y


