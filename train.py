def evaluate_model(model, X_test: np.ndarray, y_test: np.ndarray) -> None:
    from sklearn.metrics import (accuracy_score, precision_score,
                                 recall_score, f1_score, confusion_matrix,
                                 classification_report)
    import seaborn as sns

    print("\n" + "=" * 60)
    print("STEP 5 - Evaluation on Held-Out Test Set")
    print("=" * 60)

    model.eval()
    Xp = torch.from_numpy(X_test).to(DEVICE)
    with torch.no_grad():
        probs = model(Xp).cpu().numpy().ravel()
    y_pred = (probs >= 0.5).astype(int)
    y_true = y_test.astype(int).ravel()

    acc  = accuracy_score(y_true, y_pred)
    prec = precision_score(y_true, y_pred, zero_division=0)
    rec  = recall_score(y_true, y_pred, zero_division=0)
    f1   = f1_score(y_true, y_pred, zero_division=0)

    print(f"\n{'-'*45}")
    print(f"  Accuracy  : {acc  * 100:.2f} %")
    print(f"  Precision : {prec * 100:.2f} %")
    print(f"  Recall    : {rec  * 100:.2f} %")
    print(f"  F1-Score  : {f1   * 100:.2f} %")
    print(f"{'-'*45}\n")
    print(classification_report(y_true, y_pred, target_names=["Real", "Fake"]))

    cm = confusion_matrix(y_true, y_pred)
    plt.figure(figsize=(6, 5))
    sns.heatmap(cm, annot=True, fmt="d", cmap="Blues",
                xticklabels=["Real", "Fake"],
                yticklabels=["Real", "Fake"])
    plt.title("Confusion Matrix")
    plt.ylabel("True Label"); plt.xlabel("Predicted Label")
    plt.tight_layout()
    plt.savefig(str(PLOT_DIR / "confusion_matrix.png"), dpi=150)
    print(f"[INFO] Saved plots/confusion_matrix.png")


def plot_history(history: dict) -> None:
    fig, ax = plt.subplots(1, 2, figsize=(12, 4))
    ax[0].plot(history["train_acc"],  label="Train"); ax[0].plot(history["val_acc"],  label="Val")
    ax[0].set_title("Accuracy"); ax[0].legend(); ax[0].grid(alpha=0.3)
    ax[1].plot(history["train_loss"], label="Train"); ax[1].plot(history["val_loss"], label="Val")
    ax[1].set_title("Loss"); ax[1].legend(); ax[1].grid(alpha=0.3)
    plt.tight_layout()
    plt.savefig(str(PLOT_DIR / "training_curves.png"), dpi=150)
    print(f"[INFO] Saved plots/training_curves.png")


