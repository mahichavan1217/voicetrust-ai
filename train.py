def _save_clip(arr: np.ndarray, idx: int, out_dir: Path, prefix: str) -> str:
    from utils.preprocess import normalize_waveform, fix_length
    arr = normalize_waveform(arr.astype(np.float32))
    arr = fix_length(arr)
    out = str(out_dir / f"{prefix}_{idx:05d}.wav")
    save_wav(arr, out)
    return out


def _try_librispeech(max_clips: int) -> list:
    """
    LibriSpeech test-clean via HuggingFace (completely open, ~350MB total).
    Uses the 'test' split which is small enough for quick download.
    Audio: 16kHz English read speech from LibriVox audiobooks.
    """
    import librosa
    from datasets import load_dataset
    saved, idx = [], 0
    print("[INFO] Downloading LibriSpeech test-clean (real human speech)...")
    print("       This is legitimate human speech - perfect for 'Real' class.")

    # Try multiple configurations
    configs_to_try = [
        ("librispeech_asr", "clean", "test"),
        ("librispeech_asr", "clean", "validation"),
        ("librispeech_asr", "clean", "train.100"),
        ("openslr/librispeech_asr", "clean", "test"),
    ]

    ds = None
    for dataset_id, config, split in configs_to_try:
        try:
            ds = load_dataset(dataset_id, config,
                              split=split, streaming=True, trust_remote_code=False)
            print(f"[INFO] Connected to {dataset_id} ({config}/{split})")
            break
        except Exception as e:
            print(f"  [WARN] {dataset_id}/{config}/{split}: {e}")

    if ds is None:
        raise RuntimeError("All LibriSpeech sources failed.")

    for sample in tqdm(ds, total=max_clips, desc="LibriSpeech-real"):
        if idx >= max_clips:
            break
        try:
            arr = np.array(sample["audio"]["array"], dtype=np.float32)
            sr  = sample["audio"]["sampling_rate"]
            if sr != TARGET_SR:
                arr = librosa.resample(arr, orig_sr=sr, target_sr=TARGET_SR)
            path = _save_clip(arr, idx, REAL_DIR, "real")
            saved.append(path)
            idx += 1
        except Exception as e:
            pass  # skip bad samples silently
    return saved


