def _is_synthetic_data() -> bool:
    """
    Detect if data/real/ was generated by the old synthetic fallback
    by checking for a marker file written by this script.
    """
    marker = REAL_DIR / ".synthetic"
    return marker.exists()


def purge_synthetic_real():
    """Delete data/real/ if it only contains synthetic sine waves."""
    if _is_synthetic_data():
        print("[WARN] Purging old SYNTHETIC real clips (they cause bad accuracy).")
        shutil.rmtree(str(REAL_DIR))
        REAL_DIR.mkdir(parents=True, exist_ok=True)
        print("[INFO] data/real/ cleared. Will download real speech now.")
    else:
        existing = sorted(REAL_DIR.glob("real_*.wav"))
        if existing:
            print(f"[INFO] Found {len(existing)} existing real clips (kept).")


def _mark_synthetic():
    """Leave a marker so next run knows these are synthetic."""
    (REAL_DIR / ".synthetic").write_text("synthetic")


