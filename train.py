def train_model(X: np.ndarray, y: np.ndarray):
    print("\n" + "=" * 60)
    print("STEP 4 - Training CNN (PyTorch)")
    print("=" * 60)

    from sklearn.model_selection import train_test_split

    # (N, 40, 300, 1) -> (N, 1, 40, 300)
    Xp = X[:, :, :, 0][:, np.newaxis, :, :].astype(np.float32)
    yp = y.astype(np.float32).reshape(-1, 1)

    Xt, Xtmp, yt, ytmp = train_test_split(
        Xp, yp, test_size=0.30, random_state=SEED, stratify=yp)
    Xv, Xte, yv, yte = train_test_split(
        Xtmp, ytmp, test_size=0.50, random_state=SEED, stratify=ytmp)

    def mk_loader(Xa, ya, shuffle=True):
        ds = TensorDataset(torch.from_numpy(Xa), torch.from_numpy(ya))
        return DataLoader(ds, batch_size=BATCH_SIZE, shuffle=shuffle,
                          num_workers=0, pin_memory=False)

    tr_loader  = mk_loader(Xt,  yt,  shuffle=True)
    val_loader = mk_loader(Xv,  yv,  shuffle=False)
    print(f"[INFO] Train={len(Xt)}, Val={len(Xv)}, Test={len(Xte)}")

    model, optim, _ = build_cnn_model(learning_rate=5e-4)
    sched = torch.optim.lr_scheduler.CosineAnnealingLR(optim, T_max=EPOCHS)

    # Weighted BCE for class balance
    n0 = float((yt == 0).sum())
    n1 = float((yt == 1).sum())
    pos_w = torch.tensor([n0 / max(n1, 1)]).to(DEVICE)
    loss_fn = nn.BCEWithLogitsLoss(pos_weight=pos_w)

    # Use raw logits (remove sigmoid for BCEWithLogitsLoss)
    model.classifier[-1] = nn.Identity()

    history = {"train_loss": [], "val_loss": [], "train_acc": [], "val_acc": []}
    best_val, patience_cnt = float("inf"), 0
    PATIENCE = 8

    for epoch in range(1, EPOCHS + 1):
        # Train
        model.train()
        tr_loss, tr_ok, tr_n = 0.0, 0, 0
        for Xb, yb in tr_loader:
            Xb, yb = Xb.to(DEVICE), yb.to(DEVICE)
            optim.zero_grad()
            logits = model(Xb)
            loss   = loss_fn(logits, yb)
            loss.backward()
            nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            optim.step()
            tr_loss += loss.item() * len(Xb)
            tr_ok   += ((torch.sigmoid(logits) >= 0.5).float() == yb).sum().item()
            tr_n    += len(Xb)
        tr_loss /= tr_n; tr_acc = tr_ok / tr_n

        # Validate
        model.eval()
        vl, vok, vn = 0.0, 0, 0
        with torch.no_grad():
            for Xb, yb in val_loader:
                Xb, yb = Xb.to(DEVICE), yb.to(DEVICE)
                logits  = model(Xb)
                vl     += loss_fn(logits, yb).item() * len(Xb)
                vok    += ((torch.sigmoid(logits) >= 0.5).float() == yb).sum().item()
                vn     += len(Xb)
        vl /= vn; val_acc = vok / vn
        sched.step()

        history["train_loss"].append(tr_loss)
        history["val_loss"].append(vl)
        history["train_acc"].append(tr_acc)
        history["val_acc"].append(val_acc)
        print(f"  Epoch {epoch:3d}/{EPOCHS} | "
              f"loss {tr_loss:.4f}  acc {tr_acc*100:.1f}% | "
              f"val_loss {vl:.4f}  val_acc {val_acc*100:.1f}%")

        if vl < best_val - 1e-4:
            best_val = vl; patience_cnt = 0
            torch.save(model.state_dict(), "best_cnn.pt")
        else:
            patience_cnt += 1
            if patience_cnt >= PATIENCE:
                print(f"[INFO] Early stopping at epoch {epoch}.")
                break

    model.load_state_dict(torch.load("best_cnn.pt", map_location=DEVICE))
    model.eval()
    model.classifier[-1] = nn.Sigmoid()   # restore for inference
    return model, history, Xte, yte


