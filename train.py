def _generate_fake_gtts(n: int, lang: str = 'en') -> list:
    """Generate TTS audio with gTTS."""
    from gtts import gTTS
    import tempfile
    saved = []
    pool = SENTENCES if lang == 'en' else HINDI_SENTENCES
    print(f"[INFO] Generating {n} TTS clips with gTTS (lang={lang})...")

    for idx in tqdm(range(n), desc=f"gTTS-{lang}"):
        out = str(FAKE_DIR / f"fake_{idx:05d}.wav")
        if os.path.exists(out):
            saved.append(out)
            continue
        text = pool[idx % len(pool)]
        try:
            tts = gTTS(text=text, lang=lang, slow=False)
            with tempfile.NamedTemporaryFile(suffix=".mp3", delete=False) as tmp:
                tmp_path = tmp.name
            tts.save(tmp_path)
            wav = preprocess_audio(tmp_path)
            if wav is not None:
                save_wav(wav, out)
                saved.append(out)
            try:
                os.unlink(tmp_path)
            except Exception:
                pass
        except Exception as e:
            print(f"  [WARN] gTTS sample {idx}: {e}")
    return saved


def _generate_synthetic_fake(n: int) -> list:
    """Offline fallback: FM chirp signals as fake-class baseline."""
    print("[WARN] gTTS offline - generating synthetic chirp fake audio.")
    from utils.preprocess import CLIP_SAMPLES, normalize_waveform
    saved = []
    rng = np.random.default_rng(SEED + 1)
    for idx in tqdm(range(n), desc="Synth-fake"):
        t  = np.linspace(0, 3.0, CLIP_SAMPLES)
        f0 = rng.uniform(200, 600)
        sig = np.sin(2 * np.pi * (f0 + 80 * t) * t)
        sig += 0.02 * rng.standard_normal(CLIP_SAMPLES)
        out = str(FAKE_DIR / f"fake_{idx:05d}.wav")
        save_wav(normalize_waveform(sig.astype(np.float32)), out)
        saved.append(out)
    return saved


